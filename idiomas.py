def t(clave, **kwargs):
    idioma = getattr(variables_globales, "IDIOMA_ACTUAL", "es")
    tabla = _TRADUCCIONES.get(idioma, _TRADUCCIONES["es"])
    texto = tabla.get(clave, _TRADUCCIONES["es"].get(clave, clave))
    if kwargs:
        try:
            return texto.format(**kwargs)
        except (KeyError, IndexError):
            return texto
    return texto


def fuente_ajustada(texto, ancho_max_px, familia="Segoe UI", tam_base=13, tam_min=11, negrita=False):
    tam = tam_base
    while tam > tam_min:
        fuente = tkfont.Font(family=familia, size=tam, weight="bold" if negrita else "normal")
        if fuente.measure(texto) <= ancho_max_px:
            break
        tam -= 1
    return (familia, tam, "bold") if negrita else (familia, tam)